import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { describe, it } from "node:test";
import { fileURLToPath } from "node:url";

import { renderClient } from "../scripts/render.ts";

const FIXTURE_PATH: string = fileURLToPath(new URL("./fixtures/sample.openapi.json", import.meta.url));
const NAME = "sample";

async function loadFixture(): Promise<object> {
  return JSON.parse(await readFile(FIXTURE_PATH, "utf-8")) as object;
}

describe("the api client renderer", () => {
  it("starts the render with the generated banner", async () => {
    const text: string = await renderClient(await loadFixture(), NAME);
    const firstLine: string = text.split("\n")[0] ?? "";
    assert.equal(firstLine, `// Generated by scripts/generate.ts from openapi/${NAME}.json. Do not edit.`);
  });

  it("renders the paths, the components and the problem schema", async () => {
    const text: string = await renderClient(await loadFixture(), NAME);
    assert.match(text, /export interface paths/);
    assert.match(text, /export interface components/);
    assert.match(text, /Problem/);
  });

  it("renders the same text twice", async () => {
    const first: string = await renderClient(await loadFixture(), NAME);
    const second: string = await renderClient(await loadFixture(), NAME);
    assert.equal(first, second);
  });
});
